// Data cache (`cache()`) and on-demand revalidation of cached data and prerendered pages. Cached results live in
// `cacheStorage` from config.ts (process memory, or a shared store such as Redis); prerendered pages are regenerated
// by the server process that calls revalidateTag()/revalidatePath().

import { getRuntime } from "./runtime.js";

const SLOT = Symbol.for("tyvo.cache");

/** Prerendered pages of one server (registered by `createHandler()` from `@tyvo/core/server`). */
export interface PageCache {
    revalidatePath(path: string): Promise<void>;
    revalidateTag(tag: string): Promise<void>;
}

interface CacheSlot {
    pages: Set<PageCache>;
    /** Bumped by every invalidation: a run that started before one does not store its (possibly stale) result. */
    generation: number;
    /** Installed by the server while a page is prerendered: records the tags of the cached data it reads. */
    collect?: (tags: readonly string[]) => void;
}

/** @internal Shared between `@tyvo/core` and `@tyvo/core/server` (and duplicated copies of the package) through a global slot. */
export function cacheSlot(): CacheSlot {
    const globals = globalThis as { [SLOT]?: CacheSlot };
    return (globals[SLOT] ??= { pages: new Set(), generation: 0 });
}

/** One cached result, as `cacheStorage` stores it. */
export interface CacheEntry {
    /** The function's result. A storage shared between processes must serialize it (e.g. as JSON). */
    value: unknown;
    /** Epoch milliseconds after which the entry is stale; `null`: until revalidated. */
    expiresAt: number | null;
    /** Tags for `revalidateTag()`. Every entry also carries `tyvo:cache:<key>` (used by `clear()`). */
    tags: readonly string[];
}

/**
 * Backing store for `cache()` results. Export one from `config.ts` as `cacheStorage`; implement it on a shared
 * store (Redis, a database, ...) so every server process sees the same results and `revalidateTag()` reaches all of them.
 */
export interface CacheStorage {
    get(key: string): CacheEntry | undefined | null | Promise<CacheEntry | undefined | null>;
    /** `ttl`: milliseconds until the entry may be discarded, or `null` when it never expires. */
    set(key: string, entry: CacheEntry, ttl: number | null): void | Promise<void>;
    delete(key: string): void | Promise<void>;
    /** Deletes every entry whose `tags` include `tag`. */
    deleteTag(tag: string): void | Promise<void>;
}

export interface MemoryCacheOptions {
    /** How often expired entries are removed, in milliseconds. */
    sweepInterval: number;
}

/** Process-local cache storage: results are not shared between processes. Values are kept as-is (not copied). */
export function memoryCache(options: MemoryCacheOptions): CacheStorage {
    const entries = new Map<string, CacheEntry>();
    const byTag = new Map<string, Set<string>>();
    const remove = (key: string) => {
        const entry = entries.get(key);
        if (!entry) return;
        entries.delete(key);
        for (const tag of entry.tags) {
            const keys = byTag.get(tag);
            keys?.delete(key);
            if (keys?.size === 0) byTag.delete(tag);
        }
    };
    const timer = setInterval(() => {
        const now = Date.now();
        for (const [key, entry] of entries) if (entry.expiresAt !== null && entry.expiresAt <= now) remove(key);
    }, options.sweepInterval);
    timer.unref?.();

    return {
        get(key) {
            const entry = entries.get(key);
            if (entry && entry.expiresAt !== null && entry.expiresAt <= Date.now()) {
                remove(key);
                return undefined;
            }
            return entry;
        },
        set(key, entry) {
            remove(key);
            entries.set(key, entry);
            for (const tag of entry.tags) {
                let keys = byTag.get(tag);
                if (!keys) byTag.set(tag, (keys = new Set()));
                keys.add(key);
            }
        },
        delete(key) {
            remove(key);
        },
        deleteTag(tag) {
            for (const key of [...(byTag.get(tag) ?? [])]) remove(key);
        },
    };
}

export interface CacheOptions<TArgs extends unknown[]> {
    /**
     * Names this function's results in `cacheStorage`: unique per cached function and stable across the processes
     * and deploys that share the storage, e.g. `"posts.get"`. Change it when the shape of the result changes.
     */
    key: string;
    /** Seconds a result stays fresh; the next call after that runs the function again. `false`: until revalidated. */
    revalidate: number | false;
    /**
     * Tags for `revalidateTag()`: fixed, or computed from the call's arguments (`(id) => ["user:" + id]`).
     * A prerendered page that reads tagged data is regenerated by `revalidateTag()` too.
     */
    tags?: readonly string[] | ((...args: TArgs) => readonly string[]);
}

export interface CachedFunction<TArgs extends unknown[], TResult> {
    (...args: TArgs): Promise<TResult>;
    /** Drops the result cached for these arguments. */
    invalidate(...args: TArgs): Promise<void>;
    /** Drops every cached result of this function. */
    clear(): Promise<void>;
}

/**
 * Caches a function's results in `cacheStorage` (config.ts), per arguments (compared as JSON, so they must be
 * JSON-serializable). Concurrent calls with the same arguments in one process share one run; a rejected run is not cached.
 *
 * ```ts
 * export const getPost = cache(async (id: number) => db.posts.find(id), { key: "posts.get", revalidate: 60, tags: (id) => ["post:" + id] });
 * // after an update:
 * await revalidateTag("post:" + id);
 * ```
 */
export function cache<TArgs extends unknown[], TResult>(
    fn: (...args: TArgs) => TResult | Promise<TResult>,
    options: CacheOptions<TArgs>,
): CachedFunction<TArgs, Awaited<TResult>> {
    if (typeof fn !== "function") throw new TypeError("cache(): the first argument must be a function.");
    const { key, revalidate, tags } = options ?? ({} as CacheOptions<TArgs>);
    if (typeof key !== "string" || key === "") throw new TypeError('cache(): `key` must be a non-empty string naming this function, e.g. "posts.get".');
    if (revalidate !== false && !(typeof revalidate === "number" && revalidate >= 0 && Number.isFinite(revalidate))) {
        throw new TypeError("cache(): `revalidate` must be a number of seconds (>= 0) or false.");
    }
    if (tags !== undefined && typeof tags !== "function" && !Array.isArray(tags)) throw new TypeError("cache(): `tags` must be an array of strings or a function returning one.");

    const ownTag = `tyvo:cache:${key}`;
    const keyOf = (args: TArgs) => `${key}:${JSON.stringify(args)}`;
    const slot = cacheSlot();
    /** Runs in progress in this process, with the invalidation generation they started in. */
    const running = new Map<string, { run: Promise<Awaited<TResult>>; generation: number }>();

    const cached = (...args: TArgs): Promise<Awaited<TResult>> => {
        const entryTags = typeof tags === "function" ? tags(...args) : (tags ?? []);
        // A page being prerendered depends on these tags, cached or not.
        slot.collect?.(entryTags);
        const storageKey = keyOf(args);
        const generation = slot.generation;
        // Join a run only if nothing was invalidated since it started.
        const existing = running.get(storageKey);
        if (existing && existing.generation === generation) return existing.run;

        const run = (async (): Promise<Awaited<TResult>> => {
            const storage = getRuntime().cacheStorage;
            const hit = await storage.get(storageKey);
            if (hit && (hit.expiresAt === null || hit.expiresAt > Date.now())) return hit.value as Awaited<TResult>;

            const value = await fn(...args);
            // Invalidated while running: the result may predate the change, so it is returned but not stored.
            if (slot.generation === generation) {
                const ttl = revalidate === false ? null : revalidate * 1000;
                await storage.set(storageKey, { value, expiresAt: ttl === null ? null : Date.now() + ttl, tags: [...entryTags, ownTag] }, ttl);
            }
            return value;
        })();
        const entry = { run, generation };
        running.set(storageKey, entry);
        const done = () => {
            if (running.get(storageKey) === entry) running.delete(storageKey);
        };
        run.then(done, done);
        return run;
    };

    return Object.assign(cached, {
        invalidate: async (...args: TArgs) => {
            slot.generation++;
            await getRuntime().cacheStorage.delete(keyOf(args));
        },
        clear: async () => {
            slot.generation++;
            await getRuntime().cacheStorage.deleteTag(ownTag);
        },
    });
}

/**
 * Drops every `cache()` result with this tag (in `cacheStorage`) and regenerates the prerendered pages of this
 * process that read one. Resolves once those pages are regenerated.
 */
export async function revalidateTag(tag: string): Promise<void> {
    const slot = cacheSlot();
    slot.generation++;
    await getRuntime().cacheStorage.deleteTag(tag);
    await Promise.all([...slot.pages].map((pages) => pages.revalidateTag(tag)));
}

/**
 * Regenerates the prerendered page at this path (e.g. "/posts/1"; the query is ignored).
 * Resolves once it is regenerated; a path that is not prerendered is ignored.
 */
export async function revalidatePath(path: string): Promise<void> {
    await Promise.all([...cacheSlot().pages].map((pages) => pages.revalidatePath(path)));
}
