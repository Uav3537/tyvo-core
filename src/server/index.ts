export interface StartOptions extends HandlerOptions {
    port?: number;
    hostname?: string;
}

const MAX_PORT_ATTEMPTS = 10;

/** Entry point of the server bundle generated by `tyvo build`. */
export function startServer(options: StartOptions): Server {
    const handler = createHandler(options);
    const port = Number(process.env.PORT) || options.port || options.config.port;
    const settings = options.config.server;
    const hostname = options.hostname ?? (process.env.HOST || settings.hostname);

    const server = createHttpServer(
        {
            requestTimeout: settings.requestTimeout,
            headersTimeout: settings.headersTimeout,
            keepAliveTimeout: settings.keepAliveTimeout,
            maxHeaderSize: settings.maxHeaderSize,
        },
        (req, res) => {
            void serve(handler, req, res);
        },
    );
    // Like `next dev`, development moves on to the next free port; production fails with a readable message.
    let listening = port;
    server.on("error", (error: NodeJS.ErrnoException) => {
        if (error.code === "EADDRINUSE" && options.dev && listening < port + MAX_PORT_ATTEMPTS) {
            listening += 1;
            server.listen(listening, hostname);
            return;
        }
        const message =
            error.code === "EADDRINUSE"
                ? `Port ${listening} is already in use. Stop the process using it or pick another port: tyvo ${options.dev ? "dev" : "start"} --port <n>`
                : error.code === "EACCES"
                  ? `Permission denied to listen on port ${listening}. Pick a port above 1024: --port <n>`
                  : `Failed to start the server: ${error.message}`;
        emit({ type: "message", level: "error", message });
        process.exit(1);
    });
    server.listen(port, hostname, () => {
        if (listening !== port) emit({ type: "message", level: "warn", message: `Port ${port} is in use, using port ${listening} instead.` });
        // `tyvo dev` restarts this process on every change; it passes the port back so the URL stays the same.
        process.send?.({ type: "tyvo:port", port: listening });
        emit({
            type: "ready",
            level: "info",
            url: `http://${hostname ?? "localhost"}:${listening}`,
            version: tyvoVersion(),
            dev: !!options.dev,
            restart: !!options.dev && process.env.TYVO_DEV_RESTART === "1",
            // performance.now() counts from process start.
            duration: performance.now(),
            envFiles: process.env.TYVO_ENV_FILES ? process.env.TYVO_ENV_FILES.split(",") : [],
            routes: handler.router.list().map(({ pattern, file }) => ({ pattern, file })),
        });
    });

    const shutdown = () => server.close(() => process.exit(0));
    process.once("SIGINT", shutdown);
    process.once("SIGTERM", shutdown);
    return server;
}

function tyvoVersion(): string {
    try {
        return JSON.parse(readFileSync(join(packageRoot(import.meta.url), "package.json"), "utf8")).version;
    } catch {
        return "";
    }
}

async function serve(handler: FetchHandler, req: IncomingMessage, res: ServerResponse): Promise<void> {
    const controller = new AbortController();
    res.once("close", () => {
        if (!res.writableFinished) controller.abort();
    });

    try {
        const request = toRequest(req, controller.signal);
        const response = await handler(request, { ip: req.socket.remoteAddress ?? "" });
        await writeResponse(res, response);
    } catch (error) {
        // The client went away mid-response (closed tab, navigation, an event stream): nothing to report.
        if (controller.signal.aborted || (error as { code?: string }).code === "ERR_STREAM_PREMATURE_CLOSE") return;
        emit({ type: "message", level: "error", message: `Failed to write the response to ${req.method} ${req.url}`, error });
        if (!res.headersSent) res.writeHead(500, { "content-type": "application/json" });
        res.end(res.headersSent ? undefined : JSON.stringify({ error: "Internal Server Error" }));
    }
}

function toRequest(req: IncomingMessage, signal: AbortSignal): Request {
    const host = req.headers.host ?? "localhost";
    const protocol = "encrypted" in req.socket && req.socket.encrypted ? "https" : "http";
    const url = new URL(req.url ?? "/", `${protocol}://${host}`);

    const headers = new Headers();
    for (const [name, value] of Object.entries(req.headersDistinct)) {
        for (const item of value ?? []) headers.append(name, item);
    }

    const method = req.method ?? "GET";
    const hasBody = method !== "GET" && method !== "HEAD";
    return new Request(url, {
        method,
        headers,
        signal,
        body: hasBody ? (Readable.toWeb(req) as ReadableStream) : null,
        // Required by Node's fetch implementation for streaming request bodies.
        ...(hasBody ? { duplex: "half" } : {}),
    } as RequestInit);
}

async function writeResponse(res: ServerResponse, response: Response): Promise<void> {
    const headers: Record<string, string | string[]> = {};
    for (const [name, value] of response.headers) {
        if (name !== "set-cookie") headers[name] = value;
    }
    // Not in TypeScript 5.0's DOM lib, but available in every supported Node version.
    const cookies = (response.headers as Headers & { getSetCookie(): string[] }).getSetCookie();
    if (cookies.length) headers["set-cookie"] = cookies;

    res.writeHead(response.status, response.statusText || undefined, headers);
    if (!response.body) {
        res.end();
        return;
    }
    await pipeline(Readable.fromWeb(response.body as NodeReadableStream), res);
}
