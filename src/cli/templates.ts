import { readdirSync, readFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { packageRoot } from "../shared/package.js";

export interface TemplateOptions {
    /** Example routes, pages, middlewares, modifiers and server actions instead of the minimal skeleton. */
    example: boolean;
    /** Random secret written to .env.local. */
    cookieSecret: string;
}

/**
 * Files of a new project. The project itself lives in templates/base/ (templates/example/ is copied over it with
 * --example) as real files, type-checked by templates/tsconfig.json. Only package.json and tsconfig.json are built
 * here, since they depend on the Tyvo version and must not be picked up as configuration inside templates/.
 *
 * In the template files, `{{name}}`, `{{tyvoVersion}}` and `{{cookieSecret}}` are replaced (keep them inside string
 * literals so the files stay valid TypeScript), and a top-level `_x` becomes `.x`: npm drops .gitignore when publishing.
 */
export function templates(name: string, tyvoVersion: string, { example, cookieSecret }: TemplateOptions): Record<string, string> {
    const values: Record<string, string> = { name, tyvoVersion, cookieSecret };
    const fill = (text: string) =>
        text.replace(/\{\{(\w+)\}\}/g, (match, key: string) => {
            const value = values[key];
            // Escaped for the JSON and string literals the placeholders sit in.
            return value === undefined ? match : JSON.stringify(value).slice(1, -1);
        });

    const root = join(packageRoot(import.meta.url), "templates");
    const files: Record<string, string> = {};
    for (const dir of example ? ["base", "example"] : ["base"]) {
        for (const file of walk(join(root, dir))) {
            const path = relative(join(root, dir), file).split(sep).join("/");
            files[path.replace(/^_/, ".")] = fill(readFileSync(file, "utf8"));
        }
    }

    return {
        "package.json": json({
            name,
            private: true,
            type: "module",
            scripts: {
                dev: "tyvo dev",
                build: "tyvo build",
                start: "tyvo start",
                check: "tyvo check",
            },
            dependencies: {
                "@tyvo/core": `^${tyvoVersion}`,
                zod: "^4.6.7",
                react: "^19.3.1",
                "react-dom": "^19.3.1",
                "react-server-dom-turbopack": "^19.3.1",
            },
            devDependencies: {
                "@types/node": "^22.0.0",
                "@types/react": "^19.3.0",
                "@types/react-dom": "^19.3.0",
                typescript: "^5.0.4",
            },
        }),

        "tsconfig.json": json({
            compilerOptions: {
                target: "ES2022",
                lib: ["ES2023", "DOM", "DOM.Iterable"],
                jsx: "react-jsx",
                module: "ESNext",
                moduleResolution: "Bundler",
                types: ["node"],
                strict: true,
                noEmit: true,
                allowJs: false,
                isolatedModules: true,
                skipLibCheck: true,
                paths: { "@/*": ["./src/*"] },
                // `import { route } from "./$types"` in src/app/ reads the folder types tyvo generates into .tyvo/types/.
                rootDirs: [".", "./.tyvo/types"],
            },
            // .tyvo/types/: route types generated by tyvo dev/build/check/typegen (typed <Link>, href(), api()).
            include: ["**/*.ts", "**/*.tsx", ".tyvo/types/**/*.ts"],
            exclude: ["node_modules"],
        }),

        ...files,
    };
}

function* walk(dir: string): Generator<string> {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
        const full = join(dir, entry.name);
        if (entry.isDirectory()) yield* walk(full);
        else if (entry.isFile()) yield full;
    }
}

function json(value: unknown): string {
    return JSON.stringify(value, null, 4) + "\n";
}
